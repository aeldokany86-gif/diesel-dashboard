const TRANSLATABLE_PROPS = new Set([
  "aria-label",
  "placeholder",
  "title",
  "label",
  "itemLabel",
  "description",
  "note",
]);

function preserveWhitespace(original, translated) {
  const leading = String(original).match(/^\s*/)?.[0] || "";
  const trailing = String(original).match(/\s*$/)?.[0] || "";
  return `${leading}${translated}${trailing}`;
}

export function reportText(t, value, params) {
  if (typeof value !== "string") return value;
  const core = value.trim();
  if (!core) return value;

  const key = REPORT_TEXT_KEYS[core];
  if (key) {
    const translated = t(key, params);
    if (translated && translated !== key) return preserveWhitespace(value, translated);
  }

  // Translate enum-like backend values without changing their real values.
  // Examples: COMPLETED, PARTIALLY_APPROVED, EXTERNAL_SUPPLY.
  const normalizedEnum = core
    .replaceAll("_", " ")
    .toLowerCase()
    .replace(/\b\w/g, (character) => character.toUpperCase());

  if (normalizedEnum !== core) {
    const normalizedKey = REPORT_TEXT_KEYS[normalizedEnum];
    if (normalizedKey) {
      const translated = t(normalizedKey, params);
      if (translated && translated !== normalizedKey) {
        return preserveWhitespace(value, translated);
      }
    }
  }

  // Dynamic currency headings such as "Cost (SAR)" and "Total Cost (SAR)".
  const currencyHeading = core.match(/^(Cost|Total Cost|Unit Price|Total Value)\s*\(([^)]+)\)$/i);
  if (currencyHeading) {
    const label = currencyHeading[1]
      .toLowerCase()
      .replace(/\b\w/g, (character) => character.toUpperCase());
    const translatedLabel = reportText(t, label);
    return preserveWhitespace(value, `${translatedLabel} (${currencyHeading[2]})`);
  }

  const countPatterns = [
    [/^(\d+) records?$/i, "سجل"],
    [/^records?\s+(\d+)$/i, "سجل"],
    [/^(\d+) operations?$/i, "عملية"],
    [/^operations?\s+(\d+)$/i, "عملية"],
    [/^(\d+) deliveries?$/i, "توريد"],
    [/^(\d+) events?$/i, "حدث"],
    [/^(\d+) transfers?$/i, "عملية نقل"],
    [/^(\d+) assets?$/i, "معدة"],
    [/^(\d+) stations?$/i, "محطة"],
    [/^(\d+) employees?$/i, "موظف"],
    [/^(\d+) companies?$/i, "شركة"],
    [/^(\d+) projects?$/i, "مشروع"],
    [/^(\d+) reports?$/i, "تقرير"],
    [/^reports?\s+(\d+)$/i, "تقرير"],
  ];
  const language = typeof document !== "undefined" ? document.documentElement.lang : "";
  const isArabic = language === "ar" || (typeof document !== "undefined" && document.documentElement.dir === "rtl");
  if (isArabic) {
    for (const [pattern, noun] of countPatterns) {
      const match = core.match(pattern);
      if (match) return preserveWhitespace(value, `${match[1]} ${noun}`);
    }
    let match = core.match(/^(\d+) records? found$/i);
    if (match) return preserveWhitespace(value, `تم العثور على ${match[1]} سجل`);

    match = core.match(/^Showing\s+(\d+)[–-](\d+)\s+of\s+(\d+)\s+(.+)$/i);
    if (match) {
      const itemLabel = reportText(t, match[4]);
      return preserveWhitespace(
        value,
        `عرض ${match[1]}–${match[2]} من ${match[3]} ${itemLabel}`,
      );
    }

    match = core.match(/^Page (\d+) of (\d+)$/i);
    if (match) return preserveWhitespace(value, `الصفحة ${match[1]} من ${match[2]}`);
  }

  return value;
}

function localizeNode(node, t, language) {
  if (typeof node === "string") return reportText(t, node);
  if (Array.isArray(node)) return node.map((child) => localizeNode(child, t, language));
  if (!React.isValidElement(node)) return node;

  const nextProps = {};
  for (const propName of TRANSLATABLE_PROPS) {
    if (typeof node.props?.[propName] === "string") {
      nextProps[propName] = reportText(t, node.props[propName]);
    }
  }
  if (Object.prototype.hasOwnProperty.call(node.props || {}, "children")) {
    nextProps.children = React.Children.map(node.props.children, (child) =>
      localizeNode(child, t, language),
    );
  }
  if (language === "ar" && typeof node.props?.className === "string") {
    nextProps.className = node.props.className
      .replace(/\btext-left\b/g, "text-right")
      .replace(/\bright-0\b/g, "left-0")
      .replace(/\bborder-l\b/g, "border-r");
  }
  if (language === "ar" && typeof node.type === "string" && !node.props?.dir) {
    nextProps.dir = "rtl";
  }
  return React.cloneElement(node, nextProps);
}

export function ReportLocalizationBoundary({ t, language, children }) {
  return localizeNode(children, t, language);
}
